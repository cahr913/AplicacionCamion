    private void cargarCamioneroDAO(){
        CamioneroDAO listar = new CamioneroDAO();
        try{
            List<Camionero> lista = listar.listar();
            DefaultTableModel modelo = (DefaultTableModel) tblCamionero.getModel();
            modelo.setRowCount(0);
            for (Camionero c : lista){
                modelo.addRow(new Object[]{c.getIdCamionero(), c.getNombre(), c.getApellidos(),c.getDireccion(), c.getSalario(), c.getPoblacion(), c.getDpi(), c.getTelefono()});
            }
        } catch (SQLException errorSQL){
            JOptionPane.showMessageDialog(this, "Error al cargar datos: " + errorSQL);
        }
    }
    
