    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        Paquete paquete = new Paquete();
        paquete.setDescripcion(txtDescripcion.getText());
        paquete.setDestinatario(txtDestinatario.getText());
        paquete.setPeso(new BigDecimal(txtPeso.getText()));
        paquete.setDireccion(txtDireccion.getText());
        paquete.setCamionero((Camionero) cmbCamionero.getSelectedItem());
        paquete.setCiudad((Ciudad) cmbCiudad.getSelectedItem());

        PaqueteDAO dao = new PaqueteDAO();
        try {
            dao.insertar(paquete);
            JOptionPane.showMessageDialog(this, "Datos almacenados correctamente");
            cargarPaqueteDAO();
            limpiarCampos();
        } catch (SQLException error) {
            JOptionPane.showMessageDialog(this, "Error: " + error.getMessage());
        }
        
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        idPaquete = Integer.parseInt(txtId.getText());
        if (idPaquete == 0){
            JOptionPane.showMessageDialog(this, "No se ha seleccionado ningún registro");
            return;
        }
        try{
            Paquete paquete = new Paquete();
            paquete.setIdPaquete(idPaquete);
            paquete.setDescripcion(txtDescripcion.getText());
            paquete.setDestinatario(txtDestinatario.getText());
            paquete.setPeso(new BigDecimal(txtPeso.getText()));
            paquete.setDireccion(txtDireccion.getText());
            paquete.setCamionero((Camionero) cmbCamionero.getSelectedItem());
            paquete.setCiudad((Ciudad) cmbCiudad.getSelectedItem());

            PaqueteDAO dao = new PaqueteDAO();
            dao.actualizar(paquete);
            JOptionPane.showMessageDialog(this, "Datos actualizados Correctamente");
            idPaquete = 0;
            limpiarCampos();
            cargarPaqueteDAO();
        } catch (SQLException error){
            JOptionPane.showMessageDialog(this, "No se ha seleccionado ningún registro");
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        idPaquete = Integer.parseInt(txtId.getText());
        if (idPaquete == 0){
            JOptionPane.showMessageDialog(this, "No se ha seleccionado ningún registro");
            return;
        }
        int confirmar = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar este registro?", "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
        if (confirmar == JOptionPane.YES_OPTION){
            try{
                PaqueteDAO dao = new PaqueteDAO();
                dao.eliminar(idPaquete);
                JOptionPane.showMessageDialog(this, "Registro eliminado correctamente");
                idPaquete = 0;
                limpiarCampos();
                cargarPaqueteDAO();
            } catch (SQLException error){
                JOptionPane.showMessageDialog(this, "Error al eliminar: " + error.getMessage());
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblPaquetesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPaquetesMouseClicked
        // TODO add your handling code here:
        int fila = tblPaquetes.getSelectedRow();
        if (fila >= 0){
            idPaquete = Integer.parseInt(tblPaquetes.getValueAt(fila, 0).toString());
            txtId.setText(tblPaquetes.getValueAt(fila, 0).toString());
            txtDescripcion.setText(tblPaquetes.getValueAt(fila, 1).toString());
            txtDestinatario.setText(tblPaquetes.getValueAt(fila, 2).toString());
            txtPeso.setText(tblPaquetes.getValueAt(fila, 3).toString());
            txtDireccion.setText(tblPaquetes.getValueAt(fila, 4).toString());
            String camioneroStr = tblPaquetes.getValueAt(fila, 5).toString();
            String ciudadStr = tblPaquetes.getValueAt(fila, 6).toString();
            for (int i = 0; i < cmbCamionero.getItemCount(); i++){
                Camionero c = (Camionero) cmbCamionero.getItemAt(i);
                if (c.getNombre().equals(camioneroStr)){
                    cmbCamionero.setSelectedIndex(i);
                    break;
                }
            }
            for (int i = 0; i < cmbCiudad.getItemCount(); i++){
                Ciudad c = (Ciudad) cmbCiudad.getItemAt(i);
                if (c.getNombre().equals(ciudadStr)){
                    cmbCiudad.setSelectedIndex(i);
                    break;
                }
            }
        }
    }//GEN-LAST:event_tblPaquetesMouseClicked

